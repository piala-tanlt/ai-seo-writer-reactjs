import { useRef, useState } from "react";
import {
    login,
    getCurrentUser
} from "../api/auth";
export default function useLogin() {
    /*
    |--------------------------------------------------------------------------
    | Form State
    |--------------------------------------------------------------------------
    */
    const [form, setForm] = useState({
        email: "",
        password: ""
    });
    /*
    |--------------------------------------------------------------------------
    | Loading
    |--------------------------------------------------------------------------
    */
    const [loading, setLoading] = useState(false);
    /*
    |--------------------------------------------------------------------------
    | Alert
    |--------------------------------------------------------------------------
    */
    const [alert, setAlert] = useState({
        type: "",
        message: ""
    });
    /*
    |--------------------------------------------------------------------------
    | Field Errors
    |--------------------------------------------------------------------------
    */
    const [fieldErrors, setFieldErrors] = useState({
        email: false,
        password: false
    });
    /*
    |--------------------------------------------------------------------------
    | Refs
    |--------------------------------------------------------------------------
    */
    const emailRef = useRef(null);
    const passwordRef = useRef(null);
    /*
    |--------------------------------------------------------------------------
    | Shake Field
    |--------------------------------------------------------------------------
    */
    const shake = (field) => {
        setFieldErrors(prev => ({
            ...prev,
            [field]: true
        }));
        setTimeout(() => {
            setFieldErrors(prev => ({
                ...prev,
                [field]: false
            }));
        }, 400);
    };
    /*
    |--------------------------------------------------------------------------
    | Change Input
    |--------------------------------------------------------------------------
    */
    const handleChange = (field, value) => {
        setForm(prev => ({
            ...prev,
            [field]: value
        }));
        /*
        |--------------------------------------------------------------------------
        | Remove Highlight
        |--------------------------------------------------------------------------
        */
        setFieldErrors(prev => ({
            ...prev,
            [field]: false
        }));
        /*
        |--------------------------------------------------------------------------
        | Clear Error Message
        |--------------------------------------------------------------------------
        */
        setAlert({
            type: "",
            message: ""
        });
    };
    /*
    |--------------------------------------------------------------------------
    | Validate
    |--------------------------------------------------------------------------
    */
    const validate = () => {
        /*
        |--------------------------------------------------------------------------
        | Email
        |--------------------------------------------------------------------------
        */
        if (!form.email.trim()) {
            shake("email");
            emailRef.current?.focus();
            return "すべての項目を入力してください";
        }
        /*
        |--------------------------------------------------------------------------
        | Password
        |--------------------------------------------------------------------------
        */
        if (!form.password) {
            shake("password");
            passwordRef.current?.focus();
            return "すべての項目を入力してください";
        }
        return null;
    };
    /*
    |--------------------------------------------------------------------------
    | Submit Login
    |--------------------------------------------------------------------------
    */
    const handleSubmit = async () => {
        /*
        |--------------------------------------------------------------------------
        | Clear Alert
        |--------------------------------------------------------------------------
        */
        setAlert({
            type: "",
            message: ""
        });
        /*
        |--------------------------------------------------------------------------
        | Validate
        |--------------------------------------------------------------------------
        */
        const validationError = validate();
        if (validationError) {
            setAlert({
                type: "fail",
                message: validationError
            });
            return;
        }
        /*
        |--------------------------------------------------------------------------
        | Loading
        |--------------------------------------------------------------------------
        */
        setLoading(true);
        try {
            /*
            |--------------------------------------------------------------------------
            | Login
            |--------------------------------------------------------------------------
            */
            const result = await login(
                form.email.trim(),
                form.password
            );
            /*
            |--------------------------------------------------------------------------
            | Login Failed
            |--------------------------------------------------------------------------
            */
            if (!result.ok) {
                const message =
                    result.error ||
                    "無効なメールアドレスまたはパスワード";
                setAlert({
                    type: "fail",
                    message
                });
                /*
                |--------------------------------------------------------------------------
                | Highlight Email
                |--------------------------------------------------------------------------
                */
                if (
                    message.includes("メール") ||
                    message.toLowerCase().includes("email")
                ) {
                    shake("email");
                    emailRef.current?.focus();
                }
                /*
                |--------------------------------------------------------------------------
                | Highlight Password
                |--------------------------------------------------------------------------
                */
                if (
                    message.includes("パスワード") ||
                    message.toLowerCase().includes("password")
                ) {
                    shake("password");
                    passwordRef.current?.focus();
                }
                return;
            }
            /*
            |--------------------------------------------------------------------------
            | Check WordPress Session
            |--------------------------------------------------------------------------
            */
            const me = await getCurrentUser();
            if (!me.ok) {
                setAlert({
                    type: "fail",
                    message:
                        me.error ||
                        "ログイン状態を確認できませんでした。"
                });
                return;
            }
            /*
            |--------------------------------------------------------------------------
            | Login Success
            |--------------------------------------------------------------------------
            */
            console.log(
                "LOGIN SUCCESS:",
                me.user
            );
            /*
            |--------------------------------------------------------------------------
            | Redirect Dashboard
            |--------------------------------------------------------------------------
            */
            window.location.href =
                "/ai-seo-writer/dashboard/";
        } catch (error) {
            console.error(
                "LOGIN ERROR:",
                error
            );
            /*
            |--------------------------------------------------------------------------
            | Network / Unexpected Error
            |--------------------------------------------------------------------------
            */
            setAlert({
                type: "fail",
                message:
                    error?.response?.data?.error ||
                    "ログインに失敗しました。"
            });
        } finally {
            setLoading(false);
        }
    };
    /*
    |--------------------------------------------------------------------------
    | Enter Key
    |--------------------------------------------------------------------------
    */
    const handleKeyDown = (event) => {
        if (event.key === "Enter") {
            event.preventDefault();
            handleSubmit();
        }
    };
    /*
    |--------------------------------------------------------------------------
    | Return
    |--------------------------------------------------------------------------
    */
    return {
        form,
        loading,
        alert,
        fieldErrors,
        emailRef,
        passwordRef,
        handleChange,
        handleSubmit,
        handleKeyDown
    };
}